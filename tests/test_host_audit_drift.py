def test_subrun_task_hides_credentials_and_cleans_up_raw_output():
    tasks = yaml.safe_load((ROOT_DIR / "roles" / "host_audit" / "tasks" / "drift_subrun.yml").read_text(encoding="utf-8"))
    block = tasks[0]
    run = next(t for t in block["block"] if "ansible.builtin.shell" in t)
    assert run["no_log"] is True
    assert "VAULT_SECRET_ID" in run["environment"]
    assert "VAULT_SECRET_ID" not in run["ansible.builtin.shell"]
    assert "--check --diff" in run["ansible.builtin.shell"]
    assert run["environment"]["ANSIBLE_STDOUT_CALLBACK"] == "ansible.posix.json"
    cleanup = block["always"][0]
    assert cleanup["ansible.builtin.file"]["state"] == "absent"


def test_declared_play_names_match_the_playbooks():
    tasks = yaml.safe_load((ROOT_DIR / "roles" / "host_audit" / "tasks" / "drift.yml").read_text(encoding="utf-8"))
    subruns = next(t for t in tasks if "_host_audit_drift_subruns" in (t.get("ansible.builtin.set_fact") or {}))
    for sub in subruns["ansible.builtin.set_fact"]["_host_audit_drift_subruns"]:
        plays = yaml.safe_load((ROOT_DIR / "playbooks" / sub["playbook"]).read_text(encoding="utf-8"))
        names = {p.get("name") for p in plays}
        assert set(sub["plays"]) <= names, sub["playbook"]


# --- Audit Baseline participation (#125) ---------------------------------------------------------

def test_baseline_findings_use_stable_ids_and_only_fully_judged_hosts():
    section = _section({"ran": True, "rc": 0, "parsed": host_audit_drift_parse(_fixture_text(), ["hosta"], PLAYS)})
    bf = section["baseline_findings"]
    # hostb failed mid-run, hostc unreachable, c7 is Raw path: none of them may turn Drift into 해소.
    assert bf["hosts"] == ["hosta"]
    ids = {f["id"] for f in bf["findings"]}
    assert {"site:FIX-001", "site:FIX-003", "agents:FIX-001", "site:task:Unlabelled task changes"} <= ids
    assert "site:FIX-004" not in ids  # excluded as noise


def test_baseline_findings_skip_hosts_of_a_failed_subrun():
    section = _section({"ran": False, "rc": 124, "error": "시간 초과", "parsed": {}})
    assert "hosta" not in section["baseline_findings"]["hosts"]


def test_baseline_compare_marks_drift_rows():
    from host_audit_baseline import host_audit_baseline_compare, host_audit_findings_index
    section = _section({"ran": True, "rc": 0, "parsed": host_audit_drift_parse(_fixture_text(), ["hosta"], PLAYS)})
    index = host_audit_findings_index({"configuration_drift": section})
    baseline = {"sections": {"configuration_drift": {"hosts": ["hosta"], "ids": {"hosta": ["site:FIX-001", "site:SEC-999"]}}}}
    out = host_audit_baseline_compare(index, baseline, [], {"started_at": "2026-10-08T00:00:00Z", "run_id": "r2"})
    assert out["status"]["configuration_drift|hosta|site:FIX-001"] == "지속"
    assert out["status"]["configuration_drift|hosta|site:FIX-003"] == "신규"
    assert out["resolved"] == ["configuration_drift|hosta|site:SEC-999"]
