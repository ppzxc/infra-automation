        env.update(bao.env())
        res = subprocess.run(["ansible-playbook", "-i", str(tmp_path / "inv.yml"), str(tmp_path / "play.yml"), "-e", f"@{tmp_path / 'ev.yml'}"],
                             capture_output=True, text=True, env=env, cwd=tmp_path)
